-- The source users table is included without its account row.
-- Import into an isolated schema; this does not match the current backend schema.

BEGIN;

CREATE SCHEMA IF NOT EXISTS campusfind_import;

CREATE TABLE IF NOT EXISTS campusfind_import.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL,
    username VARCHAR(80) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campusfind_import.categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campusfind_import.locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL UNIQUE,
    description TEXT,
    building VARCHAR(100),
    floor VARCHAR(20),
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campusfind_import.items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    item_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    image VARCHAR(255),
    date_reported TIMESTAMP,
    date_lost_found DATE NOT NULL,
    contact_info VARCHAR(200),
    category_id INTEGER NOT NULL REFERENCES campusfind_import.categories (id),
    location_id INTEGER NOT NULL REFERENCES campusfind_import.locations (id),
    user_id INTEGER NOT NULL REFERENCES campusfind_import.users (id),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campusfind_import.claims (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INTEGER NOT NULL REFERENCES campusfind_import.items (id),
    claimant_id INTEGER NOT NULL REFERENCES campusfind_import.users (id),
    description TEXT NOT NULL,
    proof_image VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    admin_notes TEXT,
    reviewed_by INTEGER REFERENCES campusfind_import.users (id),
    reviewed_at TIMESTAMP,
    date_submitted TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS campusfind_import.admin_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL REFERENCES campusfind_import.users (id),
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(50),
    target_id INTEGER,
    details TEXT,
    timestamp TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_users_email
    ON campusfind_import.users (email);
CREATE UNIQUE INDEX IF NOT EXISTS ix_users_username
    ON campusfind_import.users (username);

